#!/bin/sh
# Stamp assets/logo.svg into Sources/wren/Logo.generated.swift so the
# binary stays single-file (no resource bundle). Run standalone after swapping
# the icon, or let scripts/build.sh call it before every build.
set -e

cd "$(dirname "$0")/.."

{
    echo "// Generated from assets/logo.svg by scripts/stamp-logo.sh."
    echo "// Replace the SVG and rerun the script; do not edit this file."
    echo "enum Logo {"
    echo "    static let svg = #\"\"\""
    cat assets/logo.svg
    echo "\"\"\"#"
    echo "}"
} > daemon/Sources/wren/Logo.generated.swift
